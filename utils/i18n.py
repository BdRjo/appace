def get_lang() -> str:
    """Get current language from Flask session (default: ar)."""
    return session.get('lang', 'ar')


def t(ar_text: str) -> str:
    """Translate Arabic text to English if lang=en, otherwise return as-is."""
    if get_lang() == 'en':
        return TRANSLATIONS.get(ar_text, ar_text)
    return ar_text


def set_lang(lang: str):
    """Set language in Flask session and sync to user.language in DB."""
    lang = lang if lang in ('ar', 'en') else 'ar'
    session['lang'] = lang
    session.permanent = True
    # ← sync to DB so email notifications arrive in the correct language
    try:
        from flask_login import current_user
        if current_user and current_user.is_authenticated:
            from utils.helpers import get_db
            from models.database import User
            db = get_db()
            u = db.query(User).get(current_user.id)
            if u and u.language != lang:
                u.language = lang
                db.commit()
    except Exception:
        pass
